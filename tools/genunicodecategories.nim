## genunicodecategories: generates ``yaml/private/unicodecategories.nim``.
##
## Usage: ``nim r tools/genunicodecategories.nim UnicodeData.txt``
##
## I-Regexp (RFC 9485), which JSONPath's ``match()`` and ``search()`` use,
## supports the character class escapes ``\p{..}`` and ``\P{..}`` for every
## Unicode General Category. Nim's ``std/unicode`` only answers a handful of
## questions (``isUpper``, ``isAlpha``, ...) and the alternative, a regex
## library like PCRE, would add NimYAML's first external dependency. So the
## category of every code point is compiled into a table instead.
##
## The table is a sorted list of *runs*: each entry is the first code point
## of a run of code points sharing a category, packed together with that
## category as ``firstCodePoint shl 5 or ord(category)``. A run lasts until
## the next entry starts, which makes lookup a binary search and keeps the
## table at a few thousand integers, compared to 1.1 million for a flat
## array. Unassigned code points form ``Cn`` runs of their own, since
## UnicodeData.txt does not list them.
##
## Download the input from
## https://www.unicode.org/Public/UCD/latest/ucd/UnicodeData.txt and pass its
## path; the generated module records the Unicode version from the file
## header comment if given with ``--version:X.Y.Z``.

import std/[os, parseopt, strutils]
when defined(nimPreviewSlimSystem):
  import std/syncio

const
  categories = ["Lu", "Ll", "Lt", "Lm", "Lo", "Mn", "Mc", "Me", "Nd", "Nl",
      "No", "Pc", "Pd", "Ps", "Pe", "Pi", "Pf", "Po", "Sm", "Sc", "Sk", "So",
      "Zs", "Zl", "Zp", "Cc", "Cf", "Cs", "Co", "Cn"]
    ## order defines the ordinal stored in the table and must match
    ## ``GeneralCategory`` in the generated module
  maxCodePoint = 0x10FFFF
  output = "yaml" / "private" / "unicodecategories.nim"

proc categoryIndex(name: string): int =
  result = categories.find(name)
  if result < 0: quit("unknown general category: " & name, 2)

proc readCategories(path: string): seq[uint8] =
  ## Returns the category of every code point. Lines whose name ends in
  ## ``, First>`` and ``, Last>`` delimit ranges that UnicodeData.txt does
  ## not spell out (CJK ideographs, Hangul syllables, private use areas).
  result = newSeq[uint8](maxCodePoint + 1)
  for c in result.mitems: c = uint8(categoryIndex("Cn"))
  var rangeStart = -1
  for line in lines(path):
    if line.len == 0: continue
    let
      fields = line.split(';')
      codePoint = parseHexInt(fields[0])
      category = uint8(categoryIndex(fields[2]))
    if fields[1].endsWith(", First>"):
      rangeStart = codePoint
    elif fields[1].endsWith(", Last>"):
      for c in rangeStart .. codePoint: result[c] = category
      rangeStart = -1
    else:
      result[codePoint] = category

proc runs(categoryOf: seq[uint8]): seq[uint32] =
  for codePoint, category in categoryOf:
    if codePoint == 0 or category != categoryOf[codePoint - 1]:
      result.add(uint32(codePoint) shl 5 or uint32(category))

proc render(table: seq[uint32], version: string): string =
  result = """#            NimYAML - YAML implementation in Nim
#        (c) Copyright 2015-2023 Felix Krause
#
#    See the file "copying.txt", included in this
#    distribution, for details about the copyright.

## The Unicode General Category of every code point, for I-Regexp's ``\p{..}``
## character class escapes. Generated by ``tools/genunicodecategories.nim``
## from UnicodeData.txt""" & (if version.len > 0: " (Unicode " & version & ")" else: "") & """;
## do not edit.
##
## ``categoryRuns`` lists runs of code points sharing a category, each packed
## as ``firstCodePoint shl 5 or ord(category)`` and lasting until the next
## run starts.

type
  GeneralCategory* = enum
    """ & categories.join(", ") & """


const categoryRuns: array[""" & $table.len & """, uint32] = [
"""
  for i in countup(0, table.high, 8):
    result.add("  ")
    for j in i ..< min(i + 8, table.len):
      result.add("0x" & toHex(table[j], 8) & "'u32,")
      if j < min(i + 8, table.len) - 1: result.add(' ')
    result.add('\n')
  result.add("""]

func generalCategory*(codePoint: int32): GeneralCategory =
  ## Returns the General Category of ``codePoint``, or ``Cn`` if it is
  ## outside of the Unicode code space.
  if codePoint < 0 or codePoint > 0x10FFFF: return Cn
  var
    low = 0
    high = categoryRuns.high
  # find the last run starting at or before codePoint
  while low < high:
    let middle = (low + high + 1) div 2
    if int32(categoryRuns[middle] shr 5) <= codePoint: low = middle
    else: high = middle - 1
  result = GeneralCategory(categoryRuns[low] and 0x1F)
""")

var
  input, version: string
for kind, key, value in getopt():
  case kind
  of cmdArgument: input = key
  of cmdLongOption, cmdShortOption:
    if key == "version": version = value
    else: quit("unknown option: " & key, 2)
  of cmdEnd: discard
if input.len == 0:
  quit("usage: genunicodecategories [--version:X.Y.Z] UnicodeData.txt", 2)
let table = runs(readCategories(input))
writeFile(output, render(table, version))
echo "wrote ", table.len, " runs to ", output
