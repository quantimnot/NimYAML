#!/usr/bin/env node
// Generates yaml-embedded.tmLanguage.json, the grammar that colours code in
// literal block scalars whose header names its language:
//
//   setup: | # python
//     import os
//
// It is injected into VS Code's YAML grammar and takes over at the `|`. Like
// that grammar's own block scalar rule its `while` is just `\G`, which holds
// as long as the enclosing mapping or sequence rule accepted the line's
// indentation, so where the block ends is YAML's decision and not
// re-implemented here. The content is tokenized by the language's own
// grammar (`include` of its scope), which must be installed.
//
// Only the comment on the header selects a grammar: sticky directives and
// key rules (see embedded/core.js) cannot be expressed in a TextMate
// grammar, so those blocks are coloured only by the semantic tokens of
// their language's server, if it provides any.
//
// Run `npm run grammar` after changing LANGUAGES; test/grammar.test.js
// checks that the grammar and package.json agree with it.

const fs = require("fs");
const path = require("path");

// [VS Code language id, scope of its grammar, other names for it in comments]
const LANGUAGES = [
  ["python", "source.python", ["py"]],
  ["shellscript", "source.shell", ["sh", "bash", "shell", "zsh"]],
  ["javascript", "source.js", ["js"]],
  ["typescript", "source.ts", ["ts"]],
  ["json", "source.json", []],
  ["sql", "source.sql", []],
  ["ruby", "source.ruby", ["rb"]],
  ["lua", "source.lua", []],
  ["go", "source.go", []],
  ["rust", "source.rust", ["rs"]],
  ["c", "source.c", []],
  ["cpp", "source.cpp", ["c++"]],
  ["csharp", "source.cs", ["cs", "c#"]],
  ["java", "source.java", []],
  ["swift", "source.swift", []],
  ["r", "source.r", []],
  ["perl", "source.perl", []],
  ["powershell", "source.powershell", ["pwsh", "ps1"]],
  ["dockerfile", "source.dockerfile", ["docker"]],
  ["makefile", "source.makefile", ["make"]],
  ["html", "text.html.derivative", []],
  ["css", "source.css", []],
  ["xml", "text.xml", []],
  ["yaml", "source.yaml", ["yml"]],
  ["ini", "source.ini", []],
  ["nim", "source.nim", []],
];

const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

function rule([id, scope, names]) {
  const alternatives = [id, ...names].map(escapeRe).join("|");
  return {
    begin: `(\\|)([1-9])?([+-])?([1-9])?[ \\t]+((#)[ \\t]*(?i:${alternatives}))[ \\t]*$`,
    while: "\\G",
    beginCaptures: {
      1: { name: "keyword.control.flow.block-scalar.literal.yaml" },
      2: { name: "constant.numeric.indentation-indicator.yaml" },
      3: { name: "storage.modifier.chomping-indicator.yaml" },
      4: { name: "constant.numeric.indentation-indicator.yaml" },
      5: { name: "comment.line.number-sign.yaml" },
      6: { name: "punctuation.definition.comment.yaml" },
    },
    name: "meta.scalar.yaml",
    patterns: [{
      begin: "$",
      while: "\\G",
      contentName: `meta.embedded.block.${id}`,
      patterns: [{ include: scope }],
    }],
  };
}

function grammar() {
  return {
    "//": "Generated by generate.js; do not edit.",
    scopeName: "nimyaml.embedded.injection",
    injectionSelector: "L:source.yaml -string -comment",
    patterns: LANGUAGES.map(([id]) => ({ include: `#${id}` })),
    repository: Object.fromEntries(LANGUAGES.map((l) => [l[0], rule(l)])),
  };
}

const output = path.join(__dirname, "yaml-embedded.tmLanguage.json");
const text = () => JSON.stringify(grammar(), null, 2) + "\n";

if (require.main === module) fs.writeFileSync(output, text());

module.exports = { LANGUAGES, output, text };
